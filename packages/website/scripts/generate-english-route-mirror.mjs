import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { basename, dirname, join, relative, sep } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import ts from "typescript";

const PACKAGE_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_APP_ROOT = join(PACKAGE_ROOT, "src", "app");
// A route file may have an English sibling next to it (opengraph-image.en.tsx
// beside opengraph-image.tsx). The /en mirror then re-exports the sibling, so
// English-only modules stay beside their German source and src/app/en keeps
// no hand-written files. Next.js ignores the sibling as a route file: its
// basename is not a reserved name.
const LOCALE_SIBLING_SUFFIX = ".en.tsx";
export const GENERATED_MARKER = "// GENERATED by scripts/generate-english-route-mirror.mjs.\n";
const MIRRORED_FILENAMES = new Set([
  "default.tsx",
  "error.tsx",
  "layout.tsx",
  "loading.tsx",
  "not-found.tsx",
  "opengraph-image.tsx",
  "page.tsx",
  "template.tsx",
  "twitter-image.tsx",
]);
const EXCLUDED_TOP_LEVEL_SEGMENTS = new Set(["api", "auth", "en", "llms.txt"]);
const ALLOWED_ROUTE_EXPORTS = [
  "alt",
  "contentType",
  "dynamic",
  "dynamicParams",
  "fetchCache",
  "generateImageMetadata",
  "generateMetadata",
  "generateStaticParams",
  "generateViewport",
  "maxDuration",
  "metadata",
  "preferredRegion",
  "revalidate",
  "runtime",
  "size",
  "viewport",
];
const STATIC_ROUTE_CONFIG_EXPORTS = new Set([
  "dynamic",
  "dynamicParams",
  "fetchCache",
  "maxDuration",
  "preferredRegion",
  "revalidate",
  "runtime",
]);

function walk(directory, appRoot) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const absolute = join(directory, entry.name);
    if (entry.isDirectory()) {
      if (directory === appRoot && EXCLUDED_TOP_LEVEL_SEGMENTS.has(entry.name)) {
        return [];
      }
      return walk(absolute, appRoot);
    }
    return [absolute];
  });
}

function localeSiblingBase(filename) {
  return filename.endsWith(LOCALE_SIBLING_SUFFIX)
    ? `${filename.slice(0, -LOCALE_SIBLING_SUFFIX.length)}.tsx`
    : null;
}

function normalizedRelative(from, to) {
  const value = relative(from, to).split(sep).join("/").replace(/\.tsx$/, "");
  return value.startsWith(".") ? value : `./${value}`;
}

function hasExportModifier(node) {
  return node.modifiers?.some(
    (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword,
  );
}

function analyzeRouteModule(source, sourceRelative) {
  const sourceFile = ts.createSourceFile(
    sourceRelative,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TSX,
  );
  const exportedNames = new Set();
  const staticRouteConfig = new Map();
  let hasDefaultExport = false;
  let client = false;

  for (const statement of sourceFile.statements) {
    if (
      ts.isExpressionStatement(statement) &&
      ts.isStringLiteral(statement.expression)
    ) {
      if (statement.expression.text === "use client") client = true;
      continue;
    }
    break;
  }

  for (const statement of sourceFile.statements) {
    if (ts.isExportAssignment(statement) && !statement.isExportEquals) {
      hasDefaultExport = true;
    }
    if (
      statement.modifiers?.some(
        (modifier) => modifier.kind === ts.SyntaxKind.DefaultKeyword,
      ) &&
      hasExportModifier(statement)
    ) {
      hasDefaultExport = true;
    }
    if (
      ts.isFunctionDeclaration(statement) &&
      hasExportModifier(statement) &&
      statement.name
    ) {
      exportedNames.add(statement.name.text);
      continue;
    }

    if (ts.isVariableStatement(statement) && hasExportModifier(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (!ts.isIdentifier(declaration.name)) continue;
        const name = declaration.name.text;
        exportedNames.add(name);
        if (STATIC_ROUTE_CONFIG_EXPORTS.has(name)) {
          if (!declaration.initializer) {
            throw new Error(
              `Static route config has no initializer: ${sourceRelative}#${name}`,
            );
          }
          staticRouteConfig.set(name, declaration.initializer.getText(sourceFile));
        }
      }
      continue;
    }

    if (
      ts.isExportDeclaration(statement) &&
      statement.exportClause &&
      ts.isNamedExports(statement.exportClause)
    ) {
      for (const element of statement.exportClause.elements) {
        exportedNames.add(element.name.text);
        if (element.name.text === "default") hasDefaultExport = true;
      }
    }
  }

  const routeExports = ALLOWED_ROUTE_EXPORTS.filter(
    (name) => exportedNames.has(name) && !STATIC_ROUTE_CONFIG_EXPORTS.has(name),
  );
  const staticDeclarations = [...STATIC_ROUTE_CONFIG_EXPORTS].flatMap((name) => {
    const initializer = staticRouteConfig.get(name);
    return initializer ? [`export const ${name} = ${initializer};`] : [];
  });

  return {
    client,
    hasDefaultExport,
    routeExports,
    staticDeclarations,
  };
}

export function expectedFiles(appRoot = DEFAULT_APP_ROOT) {
  const englishRoot = join(appRoot, "en");
  const expected = new Map();
  const sources = walk(appRoot, appRoot);
  const sourceSet = new Set(sources);
  for (const sourcePath of sources) {
    const siblingBase = localeSiblingBase(basename(sourcePath));
    if (!siblingBase) continue;
    const sourceRelative = relative(appRoot, sourcePath);
    if (!MIRRORED_FILENAMES.has(siblingBase)) {
      throw new Error(
        `English sibling has no mirrored route file name: ${sourceRelative}`,
      );
    }
    if (!sourceSet.has(join(dirname(sourcePath), siblingBase))) {
      throw new Error(
        `English sibling has no German route file beside it: ${sourceRelative}`,
      );
    }
  }

  for (const sourcePath of sources) {
    const sourceRelative = relative(appRoot, sourcePath);
    const segments = sourceRelative.split(sep);
    const filename = segments.at(-1);
    if (!filename || !MIRRORED_FILENAMES.has(filename)) continue;
    if (segments.length === 1 && filename === "layout.tsx") continue;

    const siblingPath = sourcePath.replace(/\.tsx$/, LOCALE_SIBLING_SUFFIX);
    const modulePath = sourceSet.has(siblingPath) ? siblingPath : sourcePath;
    const moduleRelative = relative(appRoot, modulePath);
    const source = readFileSync(modulePath, "utf8");
    const analysis = analyzeRouteModule(source, moduleRelative);
    if (!analysis.hasDefaultExport) {
      throw new Error(`Mirrored route module has no default export: ${moduleRelative}`);
    }

    const targetPath = join(englishRoot, sourceRelative);
    const specifier = normalizedRelative(dirname(targetPath), modulePath);
    const names = ["default", ...analysis.routeExports];
    const clientDirective = analysis.client ? '"use client";\n\n' : "";
    expected.set(
      targetPath,
      `${GENERATED_MARKER}${clientDirective}export { ${names.join(", ")} } from ${JSON.stringify(specifier)};${analysis.staticDeclarations.length > 0 ? `\n${analysis.staticDeclarations.join("\n")}` : ""}\n`,
    );
  }
  return expected;
}

// Read in one step. Checking existence first and reading afterwards leaves a
// window in which the file can change between the two calls.
function readFileIfPresent(targetPath) {
  try {
    return readFileSync(targetPath, "utf8");
  } catch (error) {
    if (error.code === "ENOENT") return null;
    throw error;
  }
}

export function syncEnglishMirror({
  appRoot = DEFAULT_APP_ROOT,
  check = false,
  reportRoot = dirname(dirname(appRoot)),
} = {}) {
  const englishRoot = join(appRoot, "en");
  const expected = expectedFiles(appRoot);
  const failures = [];

  for (const [targetPath, content] of expected) {
    const current = readFileIfPresent(targetPath);
    if (current === content) continue;
    if (check) {
      failures.push(relative(reportRoot, targetPath));
      continue;
    }
    mkdirSync(dirname(targetPath), { recursive: true });
    writeFileSync(targetPath, content, "utf8");
  }

  if (existsSync(englishRoot)) {
    for (const targetPath of walk(englishRoot, null)) {
      if (expected.has(targetPath)) continue;
      const current = readFileSync(targetPath, "utf8");
      if (!current.startsWith(GENERATED_MARKER)) {
        failures.push(`${relative(reportRoot, targetPath)} is not generator-owned`);
        continue;
      }
      if (check) failures.push(`${relative(reportRoot, targetPath)} is stale`);
      else rmSync(targetPath);
    }
  }

  if (failures.length > 0) {
    throw new Error(`English route mirror is stale:\n${failures.join("\n")}`);
  }
  return expected.size;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const check = process.argv.includes("--check");
  const count = syncEnglishMirror({ check, reportRoot: PACKAGE_ROOT });
  console.log(`${check ? "Verified" : "Generated"} ${count} English route modules.`);
}
