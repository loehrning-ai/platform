/**
 * The status rule and the quote rule of the workshop card, word for word from
 * the START file of the shipped kit (deck, kit and skill say them the same way;
 * workshops-audit-deck.test.ts holds them together). The workshop pages read
 * them as `tool`; the demo's own rule sheet says the same in full sentences.
 */
function kitCard(locale: "de" | "en"): { readonly status: string; readonly rule: string } {
  const zip = locale === "de" ? KIT_ZIP_NAME_DE : KIT_ZIP_NAME;
  const entry = `${zip.replace(/\.zip$/, "")}/${locale === "de" ? "START-HIER.md" : "START-HERE.md"}`;
  const bytes = readZipEntry(new Uint8Array(readFileSync(path.join(process.cwd(), "public/workshops/audit-vorbereitung-mit-ki", zip))), entry);
  if (!bytes) throw new Error(`kit: ${entry} is missing`);
  const words = kitVocab(locale).status;
  const opening = `${words.covered}, ${words.weak}`;
  const line = new TextDecoder().decode(bytes).split("\n").find((text) => text.includes(opening));
  if (!line) throw new Error(`kit: ${entry} has no status rule`);
  const sentences = line.slice(line.indexOf(opening)).split(/(?<=\.)\s+/);
  return { status: sentences.slice(0, -2).join(" "), rule: sentences.slice(-2).join(" ") };
}

