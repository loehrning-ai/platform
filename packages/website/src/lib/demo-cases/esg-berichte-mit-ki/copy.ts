/** From the kit, not typed here: the card's capital words (skill) and the learning objective (the kit's start file). */
function withCardWords(pack: DePack, locale: "de" | "en") {
  const words = CARD_WORDS[locale];
  const [zitat, zeitraum, umfang, freigabe] = words.checks;
  return {
    ...pack,
    checks: { zitat, zeitraum, umfang, freigabe },
    regel: {
      ...pack.regel,
      objective: OBJECTIVE[locale],
      checks: pack.regel.checkTexts.map((text, index) => [words.checks[index] ?? "", text] as [string, string]),
    },
  };
}

export type Pack = ReturnType<typeof withCardWords>;

export const COPY: { readonly de: Pack; readonly en: Pack } = { de: withCardWords(de, "de"), en: withCardWords(en, "en") };
