import { chromium } from "../../../node_modules/.bun/playwright@1.61.1/node_modules/playwright/index.mjs";
import os from "node:os";
import fs from "node:fs";
import path from "node:path";
const SHOTS = process.env.W05_SHOTS || path.join(os.tmpdir(), "w05-shots");
fs.mkdirSync(SHOTS, { recursive: true });
const LAUNCH = process.env.PW_CHROMIUM ? { executablePath: process.env.PW_CHROMIUM } : {};
const browser = await chromium.launch(LAUNCH);
const errs = [];
const ctx = await browser.newContext({ viewport: { width: 1280, height: 900 } });
const page = await ctx.newPage();
page.on("pageerror", (e) => errs.push(String(e)));
await page.goto("http://localhost:8765/sheet.html");
await page.waitForTimeout(500);
await page.screenshot({ path: SHOTS + "/sheet-desktop.png", fullPage: true });
await page.pdf({ path: SHOTS + "/sheet.pdf", format: "A4", printBackground: true, preferCSSPageSize: true });
const m = await browser.newContext({ viewport: { width: 390, height: 800 }, isMobile: true });
const p2 = await m.newPage();
await p2.goto("http://localhost:8765/sheet.html");
await p2.waitForTimeout(500);
await p2.screenshot({ path: SHOTS + "/sheet-mobile.png", fullPage: true });
const overflow = await p2.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 1);
console.log("mobile horizontal overflow:", overflow, errs.length ? errs : "no errors");
await browser.close();
